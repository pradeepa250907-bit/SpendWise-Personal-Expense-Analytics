# ==========================================

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

print("=" * 45)
print("       SPENDWISE ANALYTICS SYSTEM")
print("=" * 45)

# 1. CREATE SAMPLE DATASET

data = {
    "Date": [
        "2026-10-01", "2026-10-02", "2026-10-03",
        "2026-10-04", "2026-10-05", "2026-10-06",
        "2026-10-07", "2026-10-08", "2026-10-09",
        "2026-10-10"
    ],

    "Category": [
        "Food", "Transport", "Shopping",
        "Food", "Education", "Transport",
        "Entertainment", "Food", "Shopping",
        "Education"
    ],

    "Amount": [
        250, 100, 1200, 350, 500,
        150, 400, 300, 800, 600
    ]
}

df = pd.DataFrame(data)
df["Date"] = pd.to_datetime(df["Date"])

print("\n--- EXPENSE DATASET ---")
print(df.to_string(index=False))

# 2. BASIC DATA ANALYSIS

print("\n--- EXPENSE SUMMARY ---")

total = df["Amount"].sum()
average = df["Amount"].mean()
highest = df["Amount"].max()
lowest = df["Amount"].min()

print("Total Expense: Rs.", total)
print("Average Expense: Rs.", round(average, 2))
print("Highest Expense: Rs.", highest)
print("Lowest Expense: Rs.", lowest)

# 3. CATEGORY-WISE ANALYSIS

category_expense = df.groupby("Category")["Amount"].sum()

print("\n--- CATEGORY-WISE EXPENSE ---")
print(category_expense)

# 4. HIGHEST SPENDING CATEGORY

highest_category = category_expense.idxmax()

print("\nHighest Spending Category:", highest_category)

# 5. BUDGET MONITORING

monthly_budget = 5000

remaining = monthly_budget - total

print("\n--- BUDGET ANALYSIS ---")
print("Monthly Budget: Rs.", monthly_budget)
print("Total Spent: Rs.", total)
print("Remaining Budget: Rs.", remaining)

if total > monthly_budget:
    print("ALERT: You have exceeded your budget!")
elif total >= monthly_budget * 0.8:
    print("WARNING: You have used 80% of your budget!")
else:
    print("Your spending is within the budget.")

# 6. NUMPY ANALYSIS

amounts = np.array(df["Amount"])

print("\n--- NUMPY ANALYSIS ---")
print("Mean:", np.mean(amounts))
print("Median:", np.median(amounts))
print("Standard Deviation:", round(np.std(amounts), 2))

# 7. CATEGORY-WISE BAR CHART

plt.figure(figsize=(8, 5))

category_expense.plot(kind="bar")

plt.title("SpendWise - Category Wise Expenses")
plt.xlabel("Expense Category")
plt.ylabel("Amount (Rs.)")
plt.xticks(rotation=30)
plt.tight_layout()
plt.show()

# 8. EXPENSE DISTRIBUTION PIE CHART

plt.figure(figsize=(7, 7))

plt.pie(
    category_expense,
    labels=category_expense.index,
    autopct="%1.1f%%",
    startangle=90
)

plt.title("Expense Distribution")
plt.show()

# 9. DAILY EXPENSE TREND

daily_expense = df.groupby("Date")["Amount"].sum()

plt.figure(figsize=(9, 5))

plt.plot(
    daily_expense.index,
    daily_expense.values,
    marker="o"
)

plt.title("Daily Spending Trend")
plt.xlabel("Date")
plt.ylabel("Amount (Rs.)")
plt.xticks(rotation=45)
plt.grid(True)
plt.tight_layout()
plt.show()

# 10. SMART SPENDING RECOMMENDATIONS

print("\n--- SPENDING RECOMMENDATIONS ---")

if highest_category == "Shopping":
    print("Consider reducing unnecessary shopping expenses.")

elif highest_category == "Food":
    print("Try planning meals to control food expenses.")

elif highest_category == "Transport":
    print("Consider economical transportation options.")

elif highest_category == "Entertainment":
    print("Set a separate entertainment budget.")

else:
    print("Review your highest spending category.")

# 11. EXPORT DATASET

df.to_csv("SpendWise_Expense_Report.csv", index=False)

print("\nCSV Report Generated Successfully!")

